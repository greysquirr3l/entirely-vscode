import { describeActingLogin, type ControlConfirmation } from './controlPlaneActions';
import { isJurisdictionSlug, isTimeWindow, type DispatchFlags } from './activityFlags';
import type { AccountContext } from './accountContext';

/** Who writes the dispatch: Entire's server, or an agent installed on this machine. */
export type DispatchMode = 'cloud' | 'local';

/** What the person asked a dispatch to cover. */
export interface DispatchRequest {
	readonly mode: DispatchMode;
	/** How far back to look, as the CLI reads it: `7d`, `2 weeks ago`, an ISO date. */
	readonly since?: string;
	/** The jurisdiction whose cell generates a cloud dispatch. Absent means the home one. */
	readonly jurisdiction?: string;
	/** The repository the CLI said it would use, for the question. */
	readonly repository?: string;
}

/** Why a request cannot be sent as it is, or undefined when it can. */
export function invalidDispatchRequest(request: DispatchRequest, flags: DispatchFlags): string | undefined {
	if (request.mode === 'local' && !flags.local) {
		return 'this version of the Entire CLI cannot generate a dispatch with a local agent; update the CLI';
	}
	if (request.since !== undefined) {
		if (!isTimeWindow(request.since)) {
			return 'that time window cannot be passed to the Entire CLI';
		}
		if (!flags.since) {
			return 'this version of the Entire CLI does not describe a time window for dispatch; update the CLI';
		}
	}
	if (request.jurisdiction !== undefined) {
		if (request.mode === 'local') {
			return 'a jurisdiction applies only to a dispatch generated by Entire';
		}
		if (!isJurisdictionSlug(request.jurisdiction)) {
			return 'that jurisdiction cannot be passed to the Entire CLI';
		}
		if (!flags.jurisdiction) {
			return 'this version of the Entire CLI does not describe a jurisdiction for dispatch; update the CLI';
		}
	}
	return undefined;
}

/**
 * Arguments for one dispatch.
 *
 * Values go in the `--flag=value` form so a value can never be read as a
 * flag, and no flag the help did not describe is sent. The caller checks
 * the request first with `invalidDispatchRequest`.
 */
export function dispatchArguments(flags: DispatchFlags, request: DispatchRequest): readonly string[] {
	const args = ['dispatch'];
	if (request.mode === 'local' && flags.local) {
		args.push(flags.local);
	}
	if (request.since && flags.since) {
		args.push(`${flags.since}=${request.since}`);
	}
	if (request.mode === 'cloud' && request.jurisdiction && flags.jurisdiction) {
		args.push(`${flags.jurisdiction}=${request.jurisdiction}`);
	}
	return args;
}

/** The sentence that says how far back a dispatch looks. */
function windowWords(since: string | undefined): string {
	return since ? `since ${since}` : `over the CLI's default window`;
}

/**
 * The question asked before a dispatch is generated.
 *
 * Generating one starts work somewhere: on Entire's servers, or in an
 * agent on this machine that may use its account. It names the login it
 * will run as and says it is a single attempt.
 */
export function confirmDispatch(request: DispatchRequest, acting: Pick<AccountContext, 'handle' | 'name'>): ControlConfirmation {
	const login = describeActingLogin(acting);
	const repository = request.repository ?? 'this repository';
	if (request.mode === 'local') {
		return {
			message: `Generate a dispatch for ${repository} with a local agent?`,
			detail: [
				`The Entire CLI will run the agent installed on this machine to summarise recent work, ${windowWords(request.since)}, as ${login}.`,
				'That agent may use its own account or quota.',
				'It runs once. If it fails or is cancelled it is not started again.',
			].join('\n\n'),
			action: 'Generate Dispatch',
		};
	}
	const where = request.jurisdiction ? `the ${request.jurisdiction} jurisdiction` : 'your home jurisdiction';
	return {
		message: `Generate a dispatch for ${repository} on Entire?`,
		detail: [
			`Entire's server in ${where} will read the recorded agent work of ${repository}, ${windowWords(request.since)}, and write a summary, as ${login}.`,
			'The request is sent once. If it fails or is cancelled it is not sent again.',
		].join('\n\n'),
		action: 'Generate Dispatch',
	};
}

export type DispatchOutcome =
	| { readonly kind: 'done'; readonly text: string }
	| { readonly kind: 'empty' }
	| { readonly kind: 'cancelled' }
	| { readonly kind: 'failed'; readonly detail: string };

/** The line shown for an outcome that produced no document. */
export function describeDispatchFailure(outcome: Exclude<DispatchOutcome, { kind: 'done' }>): string {
	switch (outcome.kind) {
		case 'empty':
			return 'The Entire CLI finished but wrote no dispatch. There may be no recorded work in that window.';
		case 'cancelled':
			return 'The dispatch was cancelled. It was not started again; if Entire had already begun, it may still finish there.';
		case 'failed':
			return `The dispatch could not be generated: ${outcome.detail}. It was not retried.`;
	}
}

