const FLAGS: DispatchFlags = { local: '--local', since: '--since', jurisdiction: '--jurisdiction' };

suite('Entire dispatch request', () => {
	test('builds a cloud dispatch with the flags the help named, values attached', () => {
		const request: DispatchRequest = { mode: 'cloud', since: '3d', jurisdiction: 'eu' };
		assert.deepStrictEqual(dispatchArguments(FLAGS, request), ['dispatch', '--since=3d', '--jurisdiction=eu']);
		assert.deepStrictEqual(dispatchArguments(FLAGS, { mode: 'cloud' }), ['dispatch']);
	});

	test('builds a local dispatch and leaves the jurisdiction out', () => {
		assert.deepStrictEqual(dispatchArguments(FLAGS, { mode: 'local', since: '2 days ago' }), ['dispatch', '--local', '--since=2 days ago']);
		assert.deepStrictEqual(dispatchArguments({ ...FLAGS, local: '--on-this-machine' }, { mode: 'local' }), ['dispatch', '--on-this-machine']);
	});

	test('refuses what the help does not describe or the CLI could read as a flag', () => {
		assert.strictEqual(invalidDispatchRequest({ mode: 'cloud', since: '7d' }, FLAGS), undefined);
		assert.match(invalidDispatchRequest({ mode: 'local' }, {}) ?? '', /local agent/);
		assert.match(invalidDispatchRequest({ mode: 'cloud', since: '--local' }, FLAGS) ?? '', /time window/);
		assert.match(invalidDispatchRequest({ mode: 'cloud', since: '7d' }, {}) ?? '', /time window/);
		assert.match(invalidDispatchRequest({ mode: 'cloud', jurisdiction: 'u s' }, FLAGS) ?? '', /jurisdiction/);
		assert.match(invalidDispatchRequest({ mode: 'cloud', jurisdiction: 'us' }, {}) ?? '', /jurisdiction/);
		assert.match(invalidDispatchRequest({ mode: 'local', jurisdiction: 'us' }, FLAGS) ?? '', /only to a dispatch generated by Entire/);
	});

	test('the question names the acting login, what will run, and that it runs once', () => {
		const cloud = confirmDispatch({ mode: 'cloud', since: '7d', jurisdiction: 'eu', repository: 'gh/acme/widgets' }, ALICE);
		assert.match(cloud.message, /gh\/acme\/widgets/);
		assert.match(cloud.detail, /alice \(login alice@us\.auth\.entire\.io\)/);
		assert.match(cloud.detail, /eu jurisdiction/);
		assert.match(cloud.detail, /since 7d/);
		assert.match(cloud.detail, /not sent again/);
		assert.strictEqual(cloud.action, 'Generate Dispatch');

		const local = confirmDispatch({ mode: 'local' }, ALICE);
		assert.match(local.detail, /agent installed on this machine/);
		assert.match(local.detail, /own account or quota/);
		assert.match(local.detail, /not started again/);
		assert.match(confirmDispatch({ mode: 'cloud' }, ALICE).detail, /home jurisdiction/);
	});

	test('describes each outcome that produced no document', () => {
		assert.match(describeDispatchFailure({ kind: 'empty' }), /wrote no dispatch/);
		assert.match(describeDispatchFailure({ kind: 'cancelled' }), /not started again/);
		assert.match(describeDispatchFailure({ kind: 'failed', detail: 'boom' }), /boom.*not retried/);
	});
});

function dispatchService(cli: FakeActivityCli): DispatchService {
	return new DispatchService({ runner: cli.runner, workspaceRoot: () => cli.dir, timeoutSeconds: () => 20 });
}

suite('Entire dispatch service', () => {
	test('reads what a dispatch can be asked for from the help', async () => {
		const cli = fakeActivityCli();
		const capabilities = await dispatchService(cli).capabilities();
		assert.deepStrictEqual(capabilities, {
			ok: true,
			value: { local: true, window: true, defaultWindow: '7d', jurisdiction: true, repository: 'gh/acme/widgets' },
		});
		assert.strictEqual(cli.calls().length, 0, 'reading the help does not generate anything');
	});

	test('generates once as the confirmed login, using non-interactive output, and returns the markdown', async () => {
		const cli = fakeActivityCli();
		const outcome = await dispatchService(cli).generate({ mode: 'cloud', since: '3d', jurisdiction: 'eu' }, ALICE);
		assert.deepStrictEqual(outcome, { kind: 'done', text: DISPATCH_OUTPUT.trim() });
		assert.deepStrictEqual(cli.calls(), ['alice@us.auth.entire.io|ACCESSIBLE=1|dispatch --since=3d --jurisdiction=eu']);
	});

	test('keeps the dispatch text out of the invocation record', async () => {
		const cli = fakeActivityCli();
		await dispatchService(cli).generate({ mode: 'cloud' }, ALICE);
		const run = cli.recorded.find(entry => entry.invocation.args.includes('dispatch') && !entry.invocation.args.includes('agent-help'));
		assert.ok(run);
		assert.strictEqual(run.bodies.stdout, undefined);
	});

	test('does not retry a failure', async () => {
		const cli = fakeActivityCli({ fail: { dispatch: 'jurisdiction not found for this repository' } });
		const outcome = await dispatchService(cli).generate({ mode: 'cloud' }, ALICE);
		assert.ok(outcome.kind === 'failed' && /jurisdiction not found/.test(outcome.detail));
		assert.strictEqual(cli.callsTo('dispatch').length, 1);
	});

	test('reports a dispatch with no text as empty', async () => {
		const cli = fakeActivityCli({ dispatch: '\n' });
		assert.deepStrictEqual(await dispatchService(cli).generate({ mode: 'cloud' }, ALICE), { kind: 'empty' });
	});

	test('stops a dispatch that is cancelled, and does not start it again', async () => {
		const cli = fakeActivityCli({ slowDispatch: 5 });
		const controller = new AbortController();
		const pending = dispatchService(cli).generate({ mode: 'cloud' }, ALICE, controller.signal);
		setTimeout(() => controller.abort(), 300);
		assert.deepStrictEqual(await pending, { kind: 'cancelled' });
		assert.strictEqual(cli.callsTo('dispatch').length, 1);
	});

	test('does not run when the request does not fit the help, or the CLI is missing or old', async () => {
		const noLocal = fakeActivityCli({ helps: { dispatch: 'Flags:\n      --since string   time window (default "7d")\n' } });
		const refused = await dispatchService(noLocal).generate({ mode: 'local' }, ALICE);
		assert.ok(refused.kind === 'failed' && /local agent/.test(refused.detail));
		assert.strictEqual(noLocal.callsTo('dispatch').length, 0);

		const old = fakeActivityCli({ helps: { dispatch: null } });
		const lacking = await dispatchService(old).generate({ mode: 'cloud' }, ALICE);
		assert.ok(lacking.kind === 'failed' && /no 'dispatch' command/.test(lacking.detail));
		const capabilities = await dispatchService(old).capabilities();
		assert.ok(!capabilities.ok);

		const missing = fakeActivityCli({ noCli: true });
		const absent = await dispatchService(missing).generate({ mode: 'cloud' }, ALICE);
		assert.ok(absent.kind === 'failed' && /not installed/.test(absent.detail));
	});
});

interface Script {
	mode?: DispatchMode;
	answers?: (string | undefined)[];
	confirm?: boolean;
}

class FakeDispatchUi implements DispatchUi {
	readonly asked: { title: string; value?: string }[] = [];
	readonly confirmations: ControlConfirmation[] = [];
	readonly warnings: string[] = [];
	readonly shown: string[] = [];
	modePicks = 0;
	private readonly answers: (string | undefined)[];

	constructor(private readonly script: Script = {}) {
		this.answers = [...(script.answers ?? [])];
	}

	async pickMode(): Promise<DispatchMode | undefined> {
		this.modePicks += 1;
		return 'mode' in this.script ? this.script.mode : 'cloud';
	}

	async ask(options: { title: string; value?: string; validate: (value: string) => string | undefined }): Promise<string | undefined> {
		this.asked.push({ title: options.title, value: options.value });
		const answer = this.answers.length > 0 ? this.answers.shift() : '';
		if (answer !== undefined && options.validate(answer) !== undefined) {
			throw new Error(`the scripted answer '${answer}' fails the prompt's own validation`);
		}
		return answer;
	}

	async confirm(prompt: ControlConfirmation): Promise<boolean> {
		this.confirmations.push(prompt);
		return this.script.confirm ?? true;
	}

	withProgress<T>(_title: string, work: (signal: AbortSignal) => Promise<T>): Promise<T> {
		return work(new AbortController().signal);
	}

	async warn(message: string): Promise<void> {
		this.warnings.push(message);
	}

	async showDispatch(text: string): Promise<void> {
		this.shown.push(text);
	}
}

function dispatchDeps(cli: FakeActivityCli, ui: DispatchUi, acting: typeof ALICE | null = ALICE): DispatchDependencies {
	return { source: dispatchService(cli), acting: async () => acting ?? undefined, ui, running: { active: false } };
}

suite('Entire dispatch command', () => {
	test('asks, confirms as the acting login, generates once and opens the dispatch', async () => {
		const cli = fakeActivityCli();
		const ui = new FakeDispatchUi({ answers: ['3d', 'eu'] });
		const result = await generateDispatch(dispatchDeps(cli, ui));
		assert.strictEqual(result, 'shown');
		assert.strictEqual(ui.modePicks, 1);
		assert.strictEqual(ui.asked[0].value, '7d', 'the default window comes from the help');
		assert.strictEqual(ui.confirmations.length, 1);
		assert.match(ui.confirmations[0].detail, /alice/);
		assert.deepStrictEqual(ui.shown, [DISPATCH_OUTPUT.trim()]);
		assert.deepStrictEqual(cli.calls(), ['alice@us.auth.entire.io|ACCESSIBLE=1|dispatch --since=3d --jurisdiction=eu']);
	});

	test('runs nothing when the confirmation is declined', async () => {
		const cli = fakeActivityCli();
		const ui = new FakeDispatchUi({ confirm: false });
		assert.strictEqual(await generateDispatch(dispatchDeps(cli, ui)), 'cancelled');
		assert.strictEqual(cli.calls().length, 0);
		assert.deepStrictEqual(ui.shown, []);
	});

	test('runs nothing when a question is dismissed', async () => {
		const cli = fakeActivityCli();
		assert.strictEqual(await generateDispatch(dispatchDeps(cli, new FakeDispatchUi({ mode: undefined }))), 'cancelled');
		assert.strictEqual(await generateDispatch(dispatchDeps(cli, new FakeDispatchUi({ answers: [undefined] }))), 'cancelled');
		assert.strictEqual(await generateDispatch(dispatchDeps(cli, new FakeDispatchUi({ answers: ['', undefined] }))), 'cancelled');
		assert.strictEqual(cli.calls().length, 0);
	});

	test('a local dispatch skips the jurisdiction question', async () => {
		const cli = fakeActivityCli();
		const ui = new FakeDispatchUi({ mode: 'local', answers: [''] });
		assert.strictEqual(await generateDispatch(dispatchDeps(cli, ui)), 'shown');
		assert.strictEqual(ui.asked.length, 1);
		assert.deepStrictEqual(cli.calls(), ['alice@us.auth.entire.io|ACCESSIBLE=1|dispatch --local']);
		assert.match(ui.confirmations[0].detail, /agent installed on this machine/);
	});

	test('offers only what the help describes', async () => {
		const cli = fakeActivityCli({ helps: { dispatch: 'Flags:\n      --repos strings   cloud repo slugs\n' } });
		const ui = new FakeDispatchUi();
		assert.strictEqual(await generateDispatch(dispatchDeps(cli, ui)), 'shown');
		assert.strictEqual(ui.modePicks, 0);
		assert.strictEqual(ui.asked.length, 0);
		assert.deepStrictEqual(cli.calls(), ['alice@us.auth.entire.io|ACCESSIBLE=1|dispatch']);
	});

	test('refuses without a login, and says why', async () => {
		const cli = fakeActivityCli();
		const ui = new FakeDispatchUi();
		assert.strictEqual(await generateDispatch(dispatchDeps(cli, ui, null)), 'no-login');
		assert.match(ui.warnings[0], /Sign in first/);
		assert.strictEqual(cli.calls().length, 0);
	});

	test('reports a missing command without asking anything', async () => {
		const cli = fakeActivityCli({ helps: { dispatch: null } });
		const ui = new FakeDispatchUi();
		assert.strictEqual(await generateDispatch(dispatchDeps(cli, ui)), 'unavailable');
		assert.match(ui.warnings[0], /no 'dispatch' command/);
		assert.strictEqual(ui.confirmations.length, 0);
	});

	test('reports a failure once and does not try again', async () => {
		const cli = fakeActivityCli({ fail: { dispatch: 'server error' } });
		const ui = new FakeDispatchUi();
		assert.strictEqual(await generateDispatch(dispatchDeps(cli, ui)), 'failed');
		assert.match(ui.warnings[0], /server error.*not retried/);
		assert.strictEqual(cli.callsTo('dispatch').length, 1);
		assert.deepStrictEqual(ui.shown, []);
	});

	test('refuses a second dispatch while one is being generated', async () => {
		const cli = fakeActivityCli();
		const ui = new FakeDispatchUi();
		const deps = { ...dispatchDeps(cli, ui), running: { active: true } };
		assert.strictEqual(await generateDispatch(deps), 'busy');
		assert.match(ui.warnings[0], /already being generated/);
		assert.strictEqual(deps.running.active, true, 'the other run keeps its claim');
	});

	test('copies the dispatch text, or says there is nothing to copy', async () => {
		const written: string[] = [];
		const notes: string[] = [];
		const clipboard = { write: async (text: string) => void written.push(text) };
		const notify = async (message: string) => void notes.push(message);
		assert.strictEqual(await copyGenerated('# Dispatch', 'dispatch', clipboard, notify), true);
		assert.deepStrictEqual(written, ['# Dispatch']);
		assert.strictEqual(await copyGenerated(undefined, 'dispatch', clipboard, notify), false);
		assert.strictEqual(await copyGenerated('', 'dispatch', clipboard, notify), false);
		assert.deepStrictEqual(written, ['# Dispatch']);
		assert.match(notes[1], /no dispatch to copy/);
	});
});

suite('Entire generated documents', () => {
	async function closeAll(): Promise<void> {
		await vscode.commands.executeCommand('workbench.action.closeAllEditors');
	}

	test('a dispatch opens in an editor that cannot be edited, and its text can be copied', async () => {
		const documents = new GeneratedDocuments();
		const registration = vscode.workspace.registerTextDocumentContentProvider(GENERATED_SCHEME, documents);
		try {
			const ui = new EditorGeneratedUi(documents);
			await ui.showDispatch(DISPATCH_OUTPUT);
			const editor = vscode.window.activeTextEditor;
			assert.ok(editor, 'an editor opened');
			assert.strictEqual(editor.document.uri.scheme, GENERATED_SCHEME);
			assert.strictEqual(editor.document.languageId, 'markdown');
			assert.strictEqual(editor.document.getText(), DISPATCH_OUTPUT);

			// Typing into a content-provider editor is refused. (An extension can still
			// push a WorkspaceEdit into the buffer, but nothing can save it anywhere.)
			await vscode.commands.executeCommand('type', { text: 'changed' });
			assert.strictEqual(editor.document.getText(), DISPATCH_OUTPUT, 'a generated document is read-only');
			assert.strictEqual(editor.document.isDirty, false);
			assert.notStrictEqual(vscode.workspace.fs.isWritableFileSystem(GENERATED_SCHEME), true);

			assert.strictEqual(documents.textOf(editor.document.uri), DISPATCH_OUTPUT);
			assert.strictEqual(documents.latest('dispatch'), DISPATCH_OUTPUT);
			assert.strictEqual(documents.latest('recap'), undefined);
		} finally {
			await closeAll();
			registration.dispose();
			documents.dispose();
		}
	});

	test('the copy command leaves the clipboard alone when no dispatch has been generated', async () => {
		await vscode.env.clipboard.writeText('before');
		await vscode.commands.executeCommand('entirely.copyDispatch');
		assert.strictEqual(await vscode.env.clipboard.readText(), 'before');
	});

	test('keeps only the few most recent documents', () => {
		const documents = new GeneratedDocuments();
		try {
			const first = documents.set('dispatch', 'one');
			for (let index = 0; index < 5; index += 1) {
				documents.set('recap', `r${index}`);
			}
			assert.strictEqual(documents.textOf(first), undefined);
			assert.strictEqual(documents.provideTextDocumentContent(first), '');
			assert.strictEqual(documents.latest('recap'), 'r4');
		} finally {
			documents.dispose();
		}
	});
});

function recapService(cli: FakeActivityCli): RecapService {
	return new RecapService({ runner: cli.runner, workspaceRoot: () => cli.dir, timeoutSeconds: () => 20 });
}

class FakeRecapUi implements RecapUi {
	readonly warnings: string[] = [];
	readonly shown: string[] = [];
	picked: readonly RecapPeriod[] = [];

	constructor(private readonly choose: (periods: readonly RecapPeriod[]) => RecapPeriod | undefined = periods => periods[1]) {}

	async pickPeriod(periods: readonly RecapPeriod[]): Promise<RecapPeriod | undefined> {
		this.picked = periods;
		return this.choose(periods);
	}

	withProgress<T>(_title: string, work: () => Promise<T>): Promise<T> {
		return work();
	}

	async warn(message: string): Promise<void> {
		this.warnings.push(message);
	}

	async showRecap(text: string): Promise<void> {
		this.shown.push(text);
	}
}

suite('Entire recap', () => {
	test('asks for the static recap of the chosen period and opens it', async () => {
		const cli = fakeActivityCli();
		const ui = new FakeRecapUi();
		assert.strictEqual(await showRecap({ source: recapService(cli), ui }), 'shown');
		assert.deepStrictEqual(ui.picked.map(period => period.label), ['Today only', 'Last 7 days', 'This calendar month', 'Rolling 90 days']);
		assert.deepStrictEqual(ui.shown, [RECAP_OUTPUT.trim()]);
		assert.deepStrictEqual(cli.calls(), ['none|ACCESSIBLE=1|recap --static --color=never --week']);
	});

	test('does nothing when the period is dismissed', async () => {
		const cli = fakeActivityCli();
		assert.strictEqual(await showRecap({ source: recapService(cli), ui: new FakeRecapUi(() => undefined) }), 'cancelled');
		assert.strictEqual(cli.calls().length, 0);
	});

	test('never runs the interactive recap when the help has no static flag', async () => {
		const options: FakeActivityOptions = { helps: { recap: 'Flags:\n      --week   Last 7 days\n' } };
		const cli = fakeActivityCli(options);
		const ui = new FakeRecapUi();
		assert.strictEqual(await showRecap({ source: recapService(cli), ui }), 'failed');
		assert.match(ui.warnings[0], /static text/);
		assert.strictEqual(cli.calls().length, 0);
	});

	test('says when the CLI has no recap command, or fails', async () => {
		const old = fakeActivityCli({ helps: { recap: null } });
		const ui = new FakeRecapUi();
		assert.strictEqual(await showRecap({ source: recapService(old), ui }), 'failed');
		assert.match(ui.warnings[0], /no 'recap' command/);

		const failing = fakeActivityCli({ fail: { recap: 'not logged in' } });
		const second = new FakeRecapUi();
		assert.strictEqual(await showRecap({ source: recapService(failing), ui: second }), 'failed');
		assert.match(second.warnings[0], /not logged in/);

		const empty = fakeActivityCli({ recap: '' });
		const third = new FakeRecapUi();
		assert.strictEqual(await showRecap({ source: recapService(empty), ui: third }), 'failed');
		assert.match(third.warnings[0], /no recap/);
	});

	test('opens a recap in a read-only editor of its own', async () => {
		const documents = new GeneratedDocuments();
		const registration = vscode.workspace.registerTextDocumentContentProvider(GENERATED_SCHEME, documents);
		try {
			await new EditorGeneratedUi(documents).showRecap(RECAP_OUTPUT);
			const editor = vscode.window.activeTextEditor;
			assert.ok(editor && editor.document.uri.scheme === GENERATED_SCHEME);
			assert.strictEqual(editor.document.languageId, 'plaintext');
			assert.strictEqual(editor.document.getText(), RECAP_OUTPUT);
		} finally {
			await vscode.commands.executeCommand('workbench.action.closeAllEditors');
			registration.dispose();
			documents.dispose();
		}
	});
});
